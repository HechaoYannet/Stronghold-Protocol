// nailong/build/build.mjs — 把 nailong/ 里的声明式定制编译成 gen/ 下的运行时产物。
//
// 编译产物（全部在 nailong/gen/，git 忽略，可随时整目录重建）：
//   gen/data/**                 打过补丁的 data/ 副本 → 传给 startServer({dataDir})，服务器与浏览器同时生效
//   gen/server/kits.mjs         服务端 kit 注册表（扫描 content/kits/*.js）
//   gen/server/installs.mjs     服务端每场战斗安装器（扫描 content/installs/*.js）
//   gen/server/meta.mjs         服务端休整期注册器（扫描 content/meta/*）
//   gen/web/kits.js             浏览器内容注册表（/nailong/gen/kits.js）
//   gen/web/kits/*.js           逐字复制的 kit（其 ../../sim-helpers.js 落到 /nailong/sim-helpers.js）
//   gen/web/installs/*.js       逐字复制的安装器
//   gen/web/sim/spec.js         /sim/spec.js 的包装层（把 NailongBattle 塞进 createBattleFromSpec）
//   gen/manifest.json           HTTP 覆盖表 + 资源镜像 + 统计（host 读它）

import fs from 'node:fs';
import path from 'node:path';
import { loadLayer, MANIFEST_FILE } from '../host/layer.mjs';
import { applyOps } from './patch.mjs';
import { buildTextPack } from './textpack.mjs';

const readJson = (abs, fallback = null) => { try { return JSON.parse(fs.readFileSync(abs, 'utf8')); } catch { return fallback; } };
const writeFile = (abs, text) => { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, text); };
const writeJson = (abs, value) => writeFile(abs, `${JSON.stringify(value, null, 2)}\n`);
const listFiles = (dir, ext = null) => {
  try {
    return fs.readdirSync(dir).filter((n) => !n.startsWith('.') && n !== 'README.md')
      .filter((n) => { try { return fs.statSync(path.join(dir, n)).isFile(); } catch { return false; } })
      .filter((n) => !ext || n.endsWith(ext)).sort();
  } catch { return []; }
};
const banner = (what) => `// GENERATED by nailong build — 不要手改这个文件（改 nailong/ 下的源，然后重新 build）。\n// ${what}\n`;

/** 递归复制目录（逐字）。 */
function copyTree(src, dst) {
  let n = 0;
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name);
    const d = path.join(dst, e.name);
    if (e.isDirectory()) n += copyTree(s, d);
    else if (e.isFile()) { fs.copyFileSync(s, d); n++; }
  }
  return n;
}

/** 收集 nailong/data-patches/*.json 里的补丁，按目标文件分组。 */
export function loadPatches(layerDir) {
  const dir = path.join(layerDir, 'data-patches');
  const byFile = new Map();
  const problems = [];
  for (const name of listFiles(dir, '.json')) {
    const doc = readJson(path.join(dir, name), null);
    if (!doc) { problems.push(`data-patches/${name}: 不是合法 JSON`); continue; }
    for (const p of doc.patches ?? []) {
      if (!p || typeof p.file !== 'string') { problems.push(`data-patches/${name}: 缺少 "file"`); continue; }
      if (!byFile.has(p.file)) byFile.set(p.file, []);
      byFile.get(p.file).push({ from: name, note: p.note, ops: p.ops ?? [] });
    }
  }
  return { byFile, problems };
}

/** 生成打过补丁的 data/ 副本。 */
export function buildData({ layer, log }) {
  const dst = path.join(layer.genDir, 'data');
  fs.rmSync(dst, { recursive: true, force: true });
  fs.mkdirSync(dst, { recursive: true });
  const { byFile, problems } = loadPatches(layer.layerDir);
  let files = 0;
  let applied = 0;
  const touched = [];
  for (const name of fs.readdirSync(layer.dataDir)) {
    const src = path.join(layer.dataDir, name);
    const out = path.join(dst, name);
    const st = fs.statSync(src);
    if (st.isDirectory()) { files += copyTree(src, out); continue; }
    if (!name.endsWith('.json')) { fs.copyFileSync(src, out); files++; continue; }
    const groups = byFile.get(name);
    if (!groups) { fs.copyFileSync(src, out); files++; continue; }
    const doc = readJson(src, null);
    if (doc === null) { problems.push(`data/${name}: 不是合法 JSON，已逐字复制`); fs.copyFileSync(src, out); files++; continue; }
    for (const g of groups) {
      const r = applyOps(doc, g.ops, { file: `${name} (${g.from})` });
      applied += r.applied;
      for (const p of r.problems) problems.push(p);
    }
    writeJson(out, doc);
    files++;
    touched.push(name);
  }
  for (const f of byFile.keys()) if (!fs.existsSync(path.join(layer.dataDir, f))) problems.push(`data-patches: data/${f} 不存在`);
  log(`[data] gen/data/ — ${files} 个文件，${applied} 条补丁生效${touched.length ? ` (${touched.join(', ')})` : ''}`);
  return { files, applied, problems };
}

/** 生成服务端与浏览器的内容注册表。 */
export function buildContent({ layer, log }) {
  const kitsDir = path.join(layer.layerDir, layer.cfg.sim?.kitsDir ?? 'content/kits');
  const installsDir = path.join(layer.layerDir, layer.cfg.sim?.installsDir ?? 'content/installs');
  const metaDir = path.join(layer.layerDir, layer.cfg.sim?.metaDir ?? 'content/meta');
  const kits = listFiles(kitsDir, '.js');
  const installs = listFiles(installsDir, '.js');
  const metas = listFiles(metaDir).filter((n) => n.endsWith('.js') || n.endsWith('.mjs'));

  const importLine = (rel, i) => `import __m${i} from '${rel}';`;
  const mergeKits = (files, prefix) => files.length
    ? `export const KITS = Object.freeze(Object.assign({}, ${files.map((_, i) => `__${prefix}${i}`).join(', ')}));\n`
    : 'export const KITS = Object.freeze({});\n';

  // ---- 服务端 ----
  writeFile(path.join(layer.genDir, 'server', 'kits.mjs'),
    banner(`服务端 kit 注册表：${kits.length} 个文件。`)
    + kits.map((n, i) => importLine(`../../content/kits/${n}`, i)).join('\n') + '\n'
    + (kits.length ? `const __kits = Object.assign({}, ${kits.map((_, i) => `__m${i}`).join(', ')});\n` : 'const __kits = {};\n')
    + 'export const KITS = Object.freeze(__kits);\n'
    + 'export const KIT_FILES = Object.freeze(' + JSON.stringify(kits) + ');\n');

  writeFile(path.join(layer.genDir, 'server', 'installs.mjs'),
    banner(`服务端每场战斗安装器：${installs.length} 个文件。`)
    + installs.map((n, i) => importLine(`../../content/installs/${n}`, i)).join('\n') + '\n'
    + 'export const INSTALLS = Object.freeze([' + installs.map((_, i) => `__m${i}`).join(', ') + ']);\n'
    + 'export const INSTALL_FILES = Object.freeze(' + JSON.stringify(installs) + ');\n');

  writeFile(path.join(layer.genDir, 'server', 'meta.mjs'),
    banner(`服务端休整期注册器：${metas.length} 个文件。每个默认导出 (registry) => void。`)
    + metas.map((n, i) => importLine(`../../content/meta/${n}`, i)).join('\n') + '\n'
    + 'export const METAS = Object.freeze([' + metas.map((_, i) => `__m${i}`).join(', ') + ']);\n');

  // ---- 浏览器 ----
  const webKits = path.join(layer.genDir, 'web', 'kits');
  const webInstalls = path.join(layer.genDir, 'web', 'installs');
  fs.rmSync(webKits, { recursive: true, force: true });
  fs.rmSync(webInstalls, { recursive: true, force: true });
  for (const n of kits) { fs.mkdirSync(webKits, { recursive: true }); fs.copyFileSync(path.join(kitsDir, n), path.join(webKits, n)); }
  for (const n of installs) { fs.mkdirSync(webInstalls, { recursive: true }); fs.copyFileSync(path.join(installsDir, n), path.join(webInstalls, n)); }

  writeFile(path.join(layer.genDir, 'web', 'kits.js'),
    banner(`浏览器内容注册表：kits ${kits.length} · installs ${installs.length}。`)
    + kits.map((n, i) => importLine(`./kits/${n}`, i)).join('\n')
    + (kits.length ? '\n' : '')
    + installs.map((n, i) => importLine(`./installs/${n}`, i + 1000)).join('\n')
    + (installs.length ? '\n' : '')
    + '\n' + mergeKits(kits, 'm')
    + 'export const INSTALLS = Object.freeze([' + installs.map((_, i) => `__m${1000 + i}`).join(', ') + ']);\n');

  // ---- /sim/spec.js 包装层 ----
  const overrides = [];
  if (layer.cfg.sim?.specWrapper !== false) {
    const specUrl = '/sim/spec.js';
    writeFile(path.join(layer.genDir, 'web', 'sim', 'spec.js'),
      banner('浏览器 /sim/spec.js 包装层：把定制 Battle 类交给 createBattleFromSpec。')
      + `export * from './spec.orig.js';
import { createBattleFromSpec as __nailongBase } from './spec.orig.js';
import { NailongBattle } from '/nailong/sim/battle.js';

export function createBattleFromSpec(spec, dataSource, opts = {}) {
  return __nailongBase(spec, dataSource, { ...opts, BattleClass: opts.BattleClass || NailongBattle });
}
`);
    overrides.push({ url: specUrl, file: path.join(layer.genDir, 'web', 'sim', 'spec.js'), why: '注入定制 Battle' });
    overrides.push({ url: '/sim/spec.orig.js', file: path.join(layer.repoRoot, 'server', 'sim', 'spec.js'), why: '上游 spec 的原样副本' });
  }

  log(`[content] kits ${kits.length} · installs ${installs.length} · meta ${metas.length}`);
  return { kits, installs, metas, overrides };
}

/** 扫描 assets/ 生成资源镜像表。 */
export function buildAssets({ layer, log }) {
  const src = path.join(layer.layerDir, layer.cfg.assetMirrorDir ?? 'assets');
  const mirror = [];
  const walk = (dir, rel) => {
    let entries = [];
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      if (e.name.startsWith('.')) continue;
      const abs = path.join(dir, e.name);
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(abs, r);
      else if (e.isFile() && !/^README\.md$/i.test(e.name)) mirror.push({ url: `/assets/${r}`, file: abs });
    }
  };
  walk(src, '');
  log(`[assets] 资源镜像 ${mirror.length} 个文件`);
  return mirror;
}

/** 全部重建。 */
export async function build({ log = console.log } = {}) {
  const layer = loadLayer();
  const problems = [];
  fs.rmSync(layer.genDir, { recursive: true, force: true });
  fs.mkdirSync(layer.genDir, { recursive: true });

  const data = buildData({ layer, log });
  problems.push(...data.problems);

  const text = buildTextPack({ layerDir: layer.layerDir, repoRoot: layer.repoRoot, genDir: layer.genDir, cfg: layer.cfg, log });
  problems.push(...text.problems);

  const content = buildContent({ layer, log });
  const mirror = buildAssets({ layer, log });
  // 让审图台与外部工具能读到这份清单（/nailong/gen/ 映射到 gen/web/，而清单在上一层）
  content.overrides.push({ url: '/nailong/gen/manifest.json', file: layer.manifestPath, why: '审图台读取替换清单' });

  writeJson(layer.manifestPath, {
    layer: layer.cfg.layer, version: layer.cfg.version, title: layer.cfg.title,
    defaultLang: layer.cfg.defaultLang,
    dataDir: path.join(layer.genDir, 'data'),
    webDir: layer.webDir,
    generatedWebDir: path.join(layer.genDir, 'web'),
    overrides: content.overrides,
    assetMirror: mirror,
    stats: {
      dataFiles: data.files, dataOps: data.applied,
      uiStrings: text.ui, gameTexts: text.data,
      kits: content.kits.length, installs: content.installs.length, metas: content.metas.length,
      assets: mirror.length,
    },
  });

  log(`[manifest] ${path.relative(layer.repoRoot, layer.manifestPath)}`);
  return { layer, problems, stats: { data, text, content, mirror } };
}
